"""Shared plumbing for the scripts/tools/check_*.py source checks.

A *ratchet* grandfathers today's hits in an allowlist file and fails on a new
hit AND on an allowlisted hit that no longer exists, so the list only shrinks.
Keys are `<file>: <code>` strings with no line numbers (stable across edits);
the allowlist holds one line per occurrence, so a second identical line in an
allowlisted file is still a new hit.
"""
import collections
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
EFFECTS_DIR = os.path.join(ROOT, "scripts", "effects")


def card_scripts():
    """Repo-relative paths of the per-card scripts: scripts/effects/<set>/*.gd
    (the modules in scripts/effects/*.gd ARE the engine and are not yielded)."""
    for entry in sorted(os.listdir(EFFECTS_DIR)):
        set_dir = os.path.join(EFFECTS_DIR, entry)
        if not os.path.isdir(set_dir):
            continue
        for f in sorted(os.listdir(set_dir)):
            if f.endswith(".gd"):
                yield os.path.relpath(os.path.join(set_dir, f), ROOT)


def read_lines(path):
    """A repo-relative file's lines, trailing comments stripped."""
    with open(os.path.join(ROOT, path), encoding="utf-8") as fh:
        return [strip_comment(l.rstrip("\n")) for l in fh]


def strip_comment(line):
    """Drop a trailing `# ...` that is outside a string literal."""
    quote = None
    for i, ch in enumerate(line):
        if quote:
            if ch == quote and line[i - 1] != "\\":
                quote = None
        elif ch in "\"'":
            quote = ch
        elif ch == "#":
            return line[:i]
    return line


class Hits:
    """Occurrences of ratchet keys plus where each one was seen."""

    def __init__(self):
        self.count = collections.Counter()
        self.where = collections.defaultdict(list)

    def add(self, key, location):
        self.count[key] += 1
        self.where[key].append(location)


def read_allowlist(path):
    allowed = collections.Counter()
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if line and not line.startswith("#"):
                    allowed[line] += 1
    return allowed


def run(argv, hits, allowlist, header, name, new_label, hint):
    """Standard ratchet main: `--update` rewrites the allowlist from `hits`,
    otherwise report NEW / STALE keys. Returns the process exit status."""
    rel = os.path.relpath(allowlist, ROOT)
    if "--update" in argv:
        with open(allowlist, "w", encoding="utf-8") as fh:
            fh.write("# %s\n" % header)
            fh.write("# Generated by %s --update; only ever shrink it.\n" % name)
            for key in sorted(hits.count):
                for _ in range(hits.count[key]):
                    fh.write(key + "\n")
        print("Wrote %d entries to %s" % (sum(hits.count.values()), rel))
        return 0

    allowed = read_allowlist(allowlist)
    new = hits.count - allowed
    stale = allowed - hits.count
    width = max(len(new_label), len("STALE allowlist entry"))
    for key in sorted(new):
        print("%-*s  %s  (%s)" % (width, new_label, key, ", ".join(hits.where[key])))
    for key in sorted(stale):
        print("%-*s  %s  (remove %d line(s) from %s)" % (width, "STALE allowlist entry", key, stale[key], rel))
    if new:
        print("\n" + hint)
    if new or stale:
        return 1
    print("%s: OK (%d grandfathered)" % (name, sum(allowed.values())))
    return 0
