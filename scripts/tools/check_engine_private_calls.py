#!/usr/bin/env python3
"""Ratchet: no new calls into the pure engine's private methods from other files.

A "private" method is a `func _name(` defined in scripts/core/ or
scripts/effects/. Calling one through another object (`x._name(`) couples the
caller to engine internals: when the engine changes that signature, the
caller breaks with a parse error that only a full-suite run reveals (e.g. the
board editor calling RuleActions._check_crush_for_player). Call or add a
public engine method instead.

Existing calls are grandfathered in engine_private_calls_allowlist.txt as
`<file>: <receiver>._<method>` keys (no line numbers). The check fails on a
key that is not allowlisted AND on an allowlisted key that no longer occurs,
so the list only shrinks.

Usage: python3 scripts/tools/check_engine_private_calls.py [--update]
  --update  rewrite the allowlist from the current tree (review the diff:
            additions need a reason in the PR).
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ENGINE_DIRS = ("scripts/core", "scripts/effects")
SCAN_DIRS = ("scripts", "scenes", "tests")
SKIP_FILES = {"scripts/effects/trigger_map.gd"}  # generated
ALLOWLIST = os.path.join(os.path.dirname(os.path.abspath(__file__)), "engine_private_calls_allowlist.txt")

DEF_RE = re.compile(r"^(?:static\s+)?func\s+(_[a-z]\w*)\s*\(", re.M)
CALL_RE = re.compile(r"([A-Za-z_]\w*)(?:\[[^\]]*\])?\.(_[a-z]\w*)\s*\(")


def gd_files(dirs):
    for d in dirs:
        for dirpath, _, files in os.walk(os.path.join(ROOT, d)):
            for f in sorted(files):
                if f.endswith(".gd"):
                    path = os.path.relpath(os.path.join(dirpath, f), ROOT)
                    if path not in SKIP_FILES:
                        yield path


def strip_comment(line):
    # Drop a trailing `# ...` that is outside a string literal.
    quote = None
    for i, ch in enumerate(line):
        if quote:
            if ch == quote and line[i - 1] != "\\":
                quote = None
        elif ch in "\"'":
            quote = ch
        elif ch == "#":
            return line[:i]
    return line


def engine_privates():
    defs = {}
    for path in gd_files(ENGINE_DIRS):
        with open(os.path.join(ROOT, path), encoding="utf-8") as fh:
            for name in DEF_RE.findall(fh.read()):
                defs.setdefault(name, set()).add(path)
    return defs


def find_calls(defs):
    found = {}  # key -> first "path:line"
    for path in gd_files(SCAN_DIRS):
        with open(os.path.join(ROOT, path), encoding="utf-8") as fh:
            for lineno, line in enumerate(fh, 1):
                for recv, name in CALL_RE.findall(strip_comment(line)):
                    if recv in ("self", "super") or name not in defs or path in defs[name]:
                        continue
                    found.setdefault("%s: %s.%s" % (path, recv, name), "%s:%d" % (path, lineno))
    return found


def read_allowlist():
    if not os.path.exists(ALLOWLIST):
        return set()
    with open(ALLOWLIST, encoding="utf-8") as fh:
        return {l.strip() for l in fh if l.strip() and not l.startswith("#")}


def main():
    found = find_calls(engine_privates())
    if "--update" in sys.argv:
        with open(ALLOWLIST, "w", encoding="utf-8") as fh:
            fh.write("# Grandfathered calls into scripts/core + scripts/effects private methods.\n")
            fh.write("# Generated by check_engine_private_calls.py --update; only ever shrink it.\n")
            for key in sorted(found):
                fh.write(key + "\n")
        print("Wrote %d entries to %s" % (len(found), os.path.relpath(ALLOWLIST, ROOT)))
        return 0

    allowed = read_allowlist()
    new = sorted(set(found) - allowed)
    stale = sorted(allowed - set(found))
    for key in new:
        print("NEW private engine call  %s  (%s)" % (key, found[key]))
    for key in stale:
        print("STALE allowlist entry    %s  (remove it from the allowlist)" % key)
    if new:
        print("\nCall a public engine method instead (add one to the engine if missing).")
    if new or stale:
        return 1
    print("engine private calls: OK (%d grandfathered)" % len(allowed))
    return 0


if __name__ == "__main__":
    sys.exit(main())
